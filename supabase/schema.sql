-- 7. Hồ sơ, thống kê, bảng vàng, sổ sám hối
-- ---------------------------------------------------------------------
drop function if exists public.cap_nhat_ho_so(text, text, text, text);
create or replace function public.cap_nhat_ho_so(
  p_display_name text, p_school text, p_class_name text, p_tiktok text, p_gender text default null
) returns jsonb language plpgsql security definer set search_path = public as $$
declare
  p public.profiles := public._me_for_update();
  v_name text := nullif(trim(p_display_name), '');
  v_tiktok text := public.normalize_tiktok(p_tiktok);
  v_claim integer;
begin
  if v_name is null or char_length(v_name) > 40 then
    raise exception 'Tên hiển thị cần từ 1 đến 40 kí tự.';
  end if;
  if v_tiktok is not null and v_tiktok !~ '^[a-z0-9._]{2,24}$' then
    raise exception 'Tên TikTok chỉ gồm chữ thường, số, dấu chấm, dấu gạch dưới (2–24 kí tự).';
  end if;
  if v_tiktok is not null and exists (
    select 1 from public.profiles where tiktok_username = v_tiktok and id <> p.id) then
    raise exception 'Tên TikTok này đã gắn với tài khoản khác. Nhờ thầy cô kiểm tra giúp.';
  end if;

  update public.profiles set
    display_name = v_name,
    school = nullif(trim(left(p_school, 80)), ''),
    class_name = nullif(trim(left(p_class_name, 20)), ''),
    tiktok_username = v_tiktok,
    gender = case when p_gender in ('nam', 'nu') then p_gender else gender end
  where id = p.id returning * into p;

  -- Nhận hương được tặng trước khi gắn tên TikTok
  if v_tiktok is not null then
    select coalesce(sum(so_huong), 0) into v_claim from public.pending_gifts
    where tiktok_username = v_tiktok and claimed_by is null;
    if v_claim > 0 then
      update public.pending_gifts set claimed_by = p.id, claimed_at = now()
      where tiktok_username = v_tiktok and claimed_by is null;
      update public.profiles set huong = huong + v_claim where id = p.id returning * into p;
      insert into public.huong_log (user_id, delta, reason, note)
      values (p.id, v_claim, 'tiktok', 'Nhận quà đã tặng trước khi gắn tên TikTok');
    end if;
  end if;

  return jsonb_build_object('state', public.state_json(p), 'claimed', coalesce(v_claim, 0));
end
$$;

