  elsif p_ky = 'sam_hoi' then
    return query
      select rank() over (order by pr.sam_hoi_at), pr.display_name, pr.school, pr.class_name,
             pr.level, pr.cong_duc::bigint, pr.sam_hoi_at, pr.id = auth.uid()
      from public.profiles pr
      where pr.sam_hoi_at is not null and pr.role = 'student'
      order by 1
      limit 100;
  else
    return query
      select rank() over (order by pr.level desc, pr.cong_duc desc), pr.display_name, pr.school, pr.class_name,
             pr.level, pr.cong_duc::bigint, pr.sam_hoi_at, pr.id = auth.uid()
      from public.profiles pr
      where pr.role = 'student'
      order by 1, pr.display_name
      limit 50;
  end if;
end
$$;

create or replace function public.so_sam_hoi()
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare
  v_uid uuid := auth.uid();
begin
