create table if not exists public.topics (
  id          text primary key,
  grade       smallint not null check (grade in (10, 11, 12)),
  name        text not null,
  kinh_title  text not null,
  kinh        text[] not null default '{}',
  sort_order  integer not null default 0
);

create table if not exists public.questions (
  id           bigint generated by default as identity primary key,
  topic_id     text not null references public.topics (id) on update cascade,
  level        smallint not null check (level between 1 and 4),
  content      text not null check (char_length(content) between 5 and 2000),
  options      text[] not null check (array_length(options, 1) = 4),
  answer       char(1) not null check (answer in ('A', 'B', 'C', 'D')),
  explanation  text,
  is_published boolean not null default true,
  source_key   text unique,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);
create index if not exists questions_level_idx on public.questions (level) where is_published;

create table if not exists public.profiles (
  id                  uuid primary key references auth.users (id) on delete cascade,
  display_name        text not null default 'Đệ tử mới' check (char_length(display_name) between 1 and 40),
  school              text check (char_length(school) <= 80),
  class_name          text check (char_length(class_name) <= 20),
  tiktok_username     text check (tiktok_username ~ '^[a-z0-9._]{2,24}$'),
  role                text not null default 'student' check (role in ('student', 'admin')),
  cong_duc            integer not null default 0 check (cong_duc >= 0),
  huong               integer not null default 0 check (huong >= 0),
  level               integer not null default 1 check (level >= 1),
  correct_streak      integer not null default 0,
  best_streak         integer not null default 0,
  wrong_streak        integer not null default 0,
  total_correct       integer not null default 0,
  total_wrong         integer not null default 0,
  current_question_id bigint references public.questions (id) on delete set null,
  penalty_minutes     smallint not null default 0,
  penalty_topic_id    text references public.topics (id) on delete set null,
  penalty_question_id bigint references public.questions (id) on delete set null,
  penalty_assigned_at timestamptz,
  penalty_seat_at     timestamptz,
  penalty_elapsed     numeric(10, 2) not null default 0,
  last_seen_at        timestamptz,
  sam_hoi_at          timestamptz,
  created_at          timestamptz not null default now()
);
alter table public.profiles add column if not exists last_active_at timestamptz;
alter table public.profiles add column if not exists gender text check (gender in ('nam', 'nu'));
alter table public.profiles add column if not exists question_at timestamptz;
create unique index if not exists profiles_tiktok_idx on public.profiles (tiktok_username) where tiktok_username is not null;
create index if not exists profiles_penalty_idx on public.profiles (penalty_minutes, last_seen_at) where penalty_minutes > 0;

create table if not exists public.attempts (
  id          bigint generated by default as identity primary key,
  user_id     uuid not null references public.profiles (id) on delete cascade,
  question_id bigint not null references public.questions (id) on delete cascade,
  choice      char(1) not null,
  is_correct  boolean not null,
  level       smallint not null,
  merit       integer not null default 0,
  created_at  timestamptz not null default now()
);
create index if not exists attempts_user_idx on public.attempts (user_id, created_at desc);
create index if not exists attempts_time_idx on public.attempts (created_at);

create table if not exists public.chants (
  id          bigint generated by default as identity primary key,
  user_id     uuid not null references public.profiles (id) on delete cascade,
  topic_id    text references public.topics (id) on delete set null,
  minutes     smallint not null,
  started_at  timestamptz not null default now(),
  finished_at timestamptz
);
create index if not exists chants_user_idx on public.chants (user_id, started_at desc);

create table if not exists public.huong_log (
  id         bigint generated by default as identity primary key,
  user_id    uuid not null references public.profiles (id) on delete cascade,
