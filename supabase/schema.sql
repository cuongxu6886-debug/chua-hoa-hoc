  end if;
  return jsonb_build_object(
    'last_id', (select coalesce(max(id), 0) from public.su_kien),
    'events', coalesce((
      select jsonb_agg(jsonb_build_object('id', e.id, 'loai', e.loai, 'noi_dung', e.noi_dung, 'at', e.created_at) order by e.id)
      from (select * from public.su_kien where id > p_sau order by id desc limit 30) e), '[]'::jsonb),
    'online', (select count(*) from public.profiles
               where role = 'student' and last_active_at > now() - interval '5 minutes'),
    'room', jsonb_build_object(
      'capacity', public.cfgi('room_capacity'),
      'seated', coalesce((
        select jsonb_agg(jsonb_build_object('name', s.display_name, 'me', false,
                 'remaining', greatest(0, round(s.penalty_minutes * 60 - s.penalty_elapsed)))
               order by s.penalty_seat_at)
        from public.profiles s
        where s.penalty_minutes > 0 and s.penalty_seat_at is not null
          and s.last_seen_at > now() - v_timeout), '[]'::jsonb),
      'waiting', (select count(*) from public.profiles w
                  where w.penalty_minutes > 0 and w.penalty_seat_at is null
                    and w.last_seen_at > now() - v_timeout)
    ),
    'top', coalesce((
      select jsonb_agg(jsonb_build_object('name', t.display_name, 'class_name', t.class_name,
                                          'level', t.level, 'cong_duc', t.cong_duc, 'sam_hoi', t.sam_hoi_at is not null)
                       order by t.level desc, t.cong_duc desc)
      from (select * from public.profiles where role = 'student'
            order by level desc, cong_duc desc limit 10) t), '[]'::jsonb)
  );
end
$$;

-- Cảnh chánh điện: ai đang trong chùa, ngồi gần Ông Tổ theo cấp.
-- p_ping = true: báo mình còn ở chùa (trang Chánh điện gọi 6 giây một lần).
create or replace function public.chanh_dien_dong(p_ping boolean default true)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_uid uuid := auth.uid();
begin
  if v_uid is null then
    raise exception 'Con cần vào chùa trước.';
  end if;
  if p_ping then
    update public.profiles set last_active_at = now() where id = v_uid;
  elsif not public.is_admin() then
    raise exception 'Chỉ thầy cô mới xem được toàn cảnh.';
  end if;
  return jsonb_build_object(
    'max_level', public.cfgi('max_level'),
    'people', coalesce((
      select jsonb_agg(jsonb_build_object(
               'key', left(md5(x.id::text), 12),
               'name', x.display_name,
               'gender', x.gender,
               'level', x.level,
               'sam_hoi', x.sam_hoi_at is not null,
               'phat', x.penalty_minutes > 0,
               'me', x.id = v_uid)
             order by x.level desc)
      from (select * from public.profiles
            where (greatest(last_active_at, last_seen_at) > now() - interval '3 minutes' or (p_ping and id = v_uid))
            order by (id = v_uid) desc, greatest(last_active_at, last_seen_at) desc nulls last
            limit 60) x), '[]'::jsonb)
  );
end
$$;

