  level integer, diem bigint, sam_hoi_at timestamptz, is_me boolean
) language plpgsql stable security definer set search_path = public as $$
declare
  v_week_start timestamptz := date_trunc('week', now() at time zone 'Asia/Ho_Chi_Minh') at time zone 'Asia/Ho_Chi_Minh';
begin
  if auth.uid() is null then
    raise exception 'Con cần đăng nhập trước đã.' using hint = 'auth';
  end if;
  if p_ky = 'tuan' then
    return query
      select rank() over (order by sum(a.merit) desc), pr.display_name, pr.school, pr.class_name,
             pr.level, sum(a.merit)::bigint, pr.sam_hoi_at, pr.id = auth.uid()
      from public.attempts a join public.profiles pr on pr.id = a.user_id
      where a.created_at >= v_week_start and pr.role = 'student'
      group by pr.id
      having sum(a.merit) > 0
      order by 1, pr.display_name
