create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles where id = auth.uid() and role = 'admin')
$$;

create or replace function public.tier_of(p_level integer)
returns integer language sql stable set search_path = public as $$
  select least(4, greatest(1, ceil(p_level::numeric / greatest(1, public.cfg('levels_per_tier')))))::integer
$$;

create or replace function public.normalize_tiktok(p_name text)
returns text language sql immutable as $$
  select nullif(lower(regexp_replace(trim(coalesce(p_name, '')), '^@+', '')), '')
$$;

create or replace function public.vn_today()
returns date language sql stable as $$
  select (now() at time zone 'Asia/Ho_Chi_Minh')::date
$$;

create or replace function public.ten_goi(p public.profiles)
returns text language sql stable as $$
  select p.display_name || case when p.class_name is not null then ' lớp ' || p.class_name else '' end
$$;

-- Cách Ông Tổ gọi đệ tử theo giới tính: thiện nam, tín nữ
create or replace function public.danh_xung(p public.profiles, p_hoa boolean default false)
returns text language sql stable as $$
  select case
    when p.gender = 'nam' then case when p_hoa then 'Thiện nam' else 'thiện nam' end
    when p.gender = 'nu' then case when p_hoa then 'Tín nữ' else 'tín nữ' end
    else case when p_hoa then 'Đệ tử' else 'đệ tử' end
  end
$$;

create or replace function public._su_kien(p_loai text, p_user uuid, p_noi_dung text)
returns void language sql security definer set search_path = public as $$
  insert into public.su_kien (loai, user_id, noi_dung) values (p_loai, p_user, p_noi_dung)
$$;

-- Số giây còn lại để trả lời quẻ đang xin (null nếu không giới hạn)
create or replace function public.con_lai(p public.profiles)
returns integer language sql stable set search_path = public as $$
  select case when public.cfgi('answer_seconds') > 0 and p.current_question_id is not null then
    greatest(0, public.cfgi('answer_seconds')
                - floor(extract(epoch from now() - coalesce(p.question_at, now())))::integer)
  end
$$;

create or replace function public.question_public(q public.questions)
returns jsonb language sql stable set search_path = public as $$
  select jsonb_build_object(
    'id', q.id,
    'level', q.level,
    'content', q.content,
    'options', to_jsonb(q.options),
    'topic', (select jsonb_build_object('id', t.id, 'name', t.name, 'grade', t.grade)
              from public.topics t where t.id = q.topic_id)
  )
$$;

create or replace function public.state_json(p public.profiles)
returns jsonb language sql stable set search_path = public as $$
  select jsonb_build_object(
    'id', p.id,
    'display_name', p.display_name,
    'gender', p.gender,
    'school', p.school,
    'class_name', p.class_name,
    'tiktok_username', p.tiktok_username,
    'role', p.role,
    'cong_duc', p.cong_duc,
    'huong', p.huong,
    'level', p.level,
    'tier', public.tier_of(p.level),
    'correct_streak', p.correct_streak,
    'best_streak', p.best_streak,
    'wrong_streak', p.wrong_streak,
    'total_correct', p.total_correct,
    'total_wrong', p.total_wrong,
    'sam_hoi_at', p.sam_hoi_at,
    'has_question', p.current_question_id is not null,
    'penalty', case when p.penalty_minutes > 0 then jsonb_build_object(
        'minutes', p.penalty_minutes,
        'elapsed', p.penalty_elapsed,
        'seated', p.penalty_seat_at is not null,
        'topic', (select jsonb_build_object('id', t.id, 'name', t.name, 'grade', t.grade,
                                            'kinh_title', t.kinh_title, 'kinh', to_jsonb(t.kinh))
                  from public.topics t where t.id = p.penalty_topic_id),
        'question', (select jsonb_build_object('content', q.content, 'options', to_jsonb(q.options),
                                               'answer', q.answer, 'explanation', q.explanation)
                     from public.questions q where q.id = p.penalty_question_id)
      ) else null end,
    'config', jsonb_build_object(
      'max_level', public.cfgi('max_level'),
      'levels_per_tier', public.cfgi('levels_per_tier'),
      'incense_level_boost', public.cfgi('incense_level_boost'),
      'incense_cost_merit', public.cfgi('incense_cost_merit'),
      'room_capacity', public.cfgi('room_capacity')
    )
  )
$$;

-- Tạo hồ sơ khi có tài khoản mới
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, display_name, school, class_name, gender)
  values (
    new.id,
    coalesce(nullif(trim(left(new.raw_user_meta_data ->> 'display_name', 40)), ''),
             nullif(left(split_part(coalesce(new.email, ''), '@', 1), 40), ''),
             'Đệ tử mới'),
    nullif(trim(left(new.raw_user_meta_data ->> 'school', 80)), ''),
    nullif(trim(left(new.raw_user_meta_data ->> 'class_name', 20)), ''),
    case when new.raw_user_meta_data ->> 'gender' in ('nam', 'nu') then new.raw_user_meta_data ->> 'gender' end
  )
  on conflict (id) do nothing;
  return new;
end
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- Lấy hồ sơ của người đang đăng nhập (khóa dòng để cập nhật)
create or replace function public._me_for_update()
returns public.profiles language plpgsql security definer set search_path = public as $$
declare
  p public.profiles;
begin
  if auth.uid() is null then
    raise exception 'Con cần đăng nhập trước đã.' using hint = 'auth';
  end if;
  select * into p from public.profiles where id = auth.uid() for update;
  if not found then
    raise exception 'Không tìm thấy hồ sơ đệ tử. Thử đăng xuất rồi đăng nhập lại.' using hint = 'auth';
  end if;
  return p;
end
$$;

create or replace function public._raise_if_penalty(p public.profiles)
returns void language plpgsql as $$
begin
  if p.penalty_minutes > 0 then
    raise exception 'Con còn nợ Ông Tổ % phút tụng kinh. Lên Điện Tổ trước đã.', p.penalty_minutes
      using hint = 'penalty';
  end if;
end
$$;

-- ---------------------------------------------------------------------
-- 4. Vòng chơi chính: xin quẻ → trả lời → (sai thì) lên Điện Tổ
-- ---------------------------------------------------------------------
create or replace function public.trang_thai()
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  p public.profiles;
  q public.questions;
begin
  if auth.uid() is null then
    raise exception 'Con cần đăng nhập trước đã.' using hint = 'auth';
  end if;
  select * into p from public.profiles where id = auth.uid();
  if not found then
    raise exception 'Không tìm thấy hồ sơ đệ tử.' using hint = 'auth';
  end if;
  -- Ghi sự kiện "vào chùa" cho Màn hình live (không ghi lại nếu vừa vào gần đây)
  if p.role = 'student' and (p.last_active_at is null
      or p.last_active_at < now() - make_interval(mins => public.cfgi('join_announce_gap_minutes'))) then
    perform public._su_kien('vao_chua', p.id,
      case when p.last_active_at is null
        then 'Xin chào ' || public.danh_xung(p) || ' ' || public.ten_goi(p) || ', đã đến Chùa Hóa Học. Lần đầu vào chùa.'
        else 'Xin chào ' || public.danh_xung(p) || ' ' || public.ten_goi(p) || ', đã đến Chùa Hóa Học.' end);
  end if;
  update public.profiles set last_active_at = now() where id = p.id;
  if p.current_question_id is not null then
    select * into q from public.questions where id = p.current_question_id;
  end if;
  return jsonb_build_object(
    'state', public.state_json(p),
    'question', case when q.id is not null then public.question_public(q) else null end,
    'con_lai', public.con_lai(p)
  );
end
$$;

create or replace function public.xin_que()
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  p public.profiles := public._me_for_update();
  q public.questions;
  v_tier integer := public.tier_of(p.level);
begin
  perform public._raise_if_penalty(p);

  -- Quẻ đang xin dở thì phải trả lời, không được đổi quẻ
  if p.current_question_id is not null then
    select * into q from public.questions where id = p.current_question_id and is_published;
    if found then
      if p.question_at is null then
        update public.profiles set question_at = now() where id = p.id returning * into p;
      end if;
      return jsonb_build_object('question', public.question_public(q), 'state', public.state_json(p), 'resumed', true,
                                'con_lai', public.con_lai(p));
    end if;
  end if;

  -- Ưu tiên: đúng mức, chưa từng trả lời đúng, không lặp 10 câu gần nhất
  select * into q from public.questions qq
  where qq.is_published and qq.level = v_tier
    and not exists (select 1 from public.attempts a
                    where a.user_id = p.id and a.question_id = qq.id and a.is_correct)
    and qq.id not in (select a.question_id from public.attempts a
                      where a.user_id = p.id order by a.created_at desc limit 10)
  order by random() limit 1;

  -- Hết câu mới ở mức này: lấy câu đúng mức bất kì (trừ câu vừa làm)
  if not found then
    select * into q from public.questions qq
    where qq.is_published and qq.level = v_tier
      and qq.id not in (select a.question_id from public.attempts a
                        where a.user_id = p.id order by a.created_at desc limit 3)
    order by random() limit 1;
  end if;

  -- Mức này chưa có câu nào: lấy mức gần nhất
  if not found then
    select * into q from public.questions qq
    where qq.is_published
    order by abs(qq.level - v_tier), random() limit 1;
  end if;

  if not found then
    raise exception 'Chùa chưa có câu hỏi nào. Nhờ thầy cô thêm câu hỏi trong trang Quản trị.';
  end if;

  update public.profiles set current_question_id = q.id, question_at = now() where id = p.id returning * into p;
  return jsonb_build_object('question', public.question_public(q), 'state', public.state_json(p), 'resumed', false,
                            'con_lai', public.con_lai(p));
end
$$;

create or replace function public.tra_loi(p_question_id bigint, p_choice text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  p public.profiles := public._me_for_update();
  q public.questions;
  v_choice text := upper(trim(coalesce(p_choice, '')));
  v_correct boolean;
  v_already boolean;
  v_merit integer := 0;
  v_max integer := public.cfgi('max_level');
  v_old_level integer := p.level;
  v_new_level integer;
  v_penalty integer := 0;
  v_sam_hoi boolean := false;
  v_het_gio boolean := false;
begin
  perform public._raise_if_penalty(p);
  if v_choice = 'HET_GIO' then
    v_het_gio := true;
    v_choice := '-';
  elsif v_choice not in ('A', 'B', 'C', 'D') then
    raise exception 'Đáp án phải là A, B, C hoặc D.';
  end if;
  if p.current_question_id is distinct from p_question_id then
    raise exception 'Quẻ này không còn hiệu lực. Con xin quẻ mới nhé.' using hint = 'stale';
  end if;

  select * into q from public.questions where id = p_question_id;
  if not found then
    raise exception 'Câu hỏi này đã bị xóa. Con xin quẻ mới nhé.' using hint = 'stale';
  end if;

  -- Quá giờ (cho thêm 5 giây bù mạng chậm) thì tính là sai
  if public.cfgi('answer_seconds') > 0 and p.question_at is not null
     and now() - p.question_at > make_interval(secs => public.cfgi('answer_seconds') + 5) then
    v_het_gio := true;
  end if;
  v_correct := (not v_het_gio) and (q.answer = v_choice);
  v_already := exists (select 1 from public.attempts
                       where user_id = p.id and question_id = q.id and is_correct);

  if v_correct then
    if not v_already then
      v_merit := public.cfgi('merit_tier_' || q.level);
    end if;
    v_new_level := least(v_max, p.level + public.cfgi('level_up_on_correct'));
    v_sam_hoi := v_new_level >= v_max and p.sam_hoi_at is null;
    update public.profiles set
      cong_duc = cong_duc + v_merit,
      level = v_new_level,
      correct_streak = correct_streak + 1,
      best_streak = greatest(best_streak, correct_streak + 1),
      wrong_streak = 0,
      total_correct = total_correct + 1,
      current_question_id = null,
      sam_hoi_at = case when v_sam_hoi then now() else sam_hoi_at end
    where id = p.id
    returning * into p;
  else
    v_penalty := least(public.cfgi('max_penalty_minutes'),
                       (p.wrong_streak + 1) * public.cfgi('penalty_step_minutes'));
    v_penalty := greatest(v_penalty, 1);
    v_new_level := greatest(1, p.level - public.cfgi('level_down_on_wrong'));
    update public.profiles set
      level = v_new_level,
      correct_streak = 0,
      wrong_streak = wrong_streak + 1,
      total_wrong = total_wrong + 1,
      current_question_id = null,
      penalty_minutes = v_penalty,
      penalty_topic_id = q.topic_id,
      penalty_question_id = q.id,
      penalty_assigned_at = now(),
      penalty_seat_at = null,
      penalty_elapsed = 0
    where id = p.id
    returning * into p;
  end if;

  insert into public.attempts (user_id, question_id, choice, is_correct, level, merit)
  values (p.id, q.id, v_choice, v_correct, q.level, v_merit);

  if v_sam_hoi then
    perform public._su_kien('sam_hoi', p.id,
      'Chúc mừng ' || public.danh_xung(p) || ' ' || public.ten_goi(p) || ' đã sám hối thành công, đạt cấp ' || v_max || '!');
  end if;

  return jsonb_build_object(
    'is_correct', v_correct,
    'correct_choice', q.answer,
    'explanation', q.explanation,
    'merit', v_merit,
    'already', v_already,
    'old_level', v_old_level,
    'new_level', p.level,
    'penalty_minutes', v_penalty,
    'sam_hoi', v_sam_hoi,
    'het_gio', v_het_gio,
    'state', public.state_json(p)
  );
end
$$;

-- ---------------------------------------------------------------------
-- 5. Điện Tổ: phòng ngồi phạt có giới hạn chỗ, đồng hồ tụng kinh do máy chủ giữ
-- Trang Điện Tổ gọi hàm này khoảng 10 giây một lần.
--   p_ngoi = true khi học sinh đã vái Tổ xong và xin vào ngồi.
-- Thời gian tụng chỉ được cộng khi học sinh đang ngồi và còn mở trang.
-- ---------------------------------------------------------------------
create or replace function public.dien_to(p_ngoi boolean default false)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  p public.profiles;
  v_now timestamptz := clock_timestamp();
  v_timeout interval := make_interval(secs => public.cfgi('presence_timeout_seconds'));
  v_cap integer := public.cfgi('room_capacity');
  v_tick numeric;
  v_occupied integer;
  v_ahead integer;
  v_done boolean := false;
  v_position integer;
begin
  -- Xếp chỗ lần lượt để phòng không vượt quá số chỗ
  perform pg_advisory_xact_lock(hashtext('chua_hoa_hoc_dien_to'));
  p := public._me_for_update();

  if p.penalty_minutes > 0 then
    if p.penalty_seat_at is not null then
      if p.last_seen_at is not null and v_now - p.last_seen_at <= v_timeout then
        v_tick := least(extract(epoch from (v_now - p.last_seen_at)), public.cfg('tick_cap_seconds'));
        p.penalty_elapsed := p.penalty_elapsed + greatest(v_tick, 0);
      else
        -- Rời điện quá lâu: mất chỗ, phải xếp hàng lại (giữ nguyên số giây đã tụng)
        p.penalty_seat_at := null;
      end if;
    end if;
    p.last_seen_at := v_now;

    if p.penalty_elapsed >= p.penalty_minutes * 60 then
      update public.chants set finished_at = v_now where user_id = p.id and finished_at is null;
      p.penalty_minutes := 0;
      p.penalty_topic_id := null;
      p.penalty_question_id := null;
      p.penalty_assigned_at := null;
      p.penalty_seat_at := null;
      p.penalty_elapsed := 0;
      v_done := true;
    elsif p.penalty_seat_at is null and p_ngoi then
      select count(*) into v_occupied from public.profiles
      where id <> p.id and penalty_minutes > 0 and penalty_seat_at is not null
        and last_seen_at > v_now - v_timeout;
      select count(*) into v_ahead from public.profiles
      where id <> p.id and penalty_minutes > 0 and penalty_seat_at is null
        and last_seen_at > v_now - v_timeout
        and penalty_assigned_at < p.penalty_assigned_at;
      if v_occupied + v_ahead < v_cap then
        p.penalty_seat_at := v_now;
        if not exists (select 1 from public.chants where user_id = p.id and finished_at is null) then
          insert into public.chants (user_id, topic_id, minutes, started_at)
          values (p.id, p.penalty_topic_id, p.penalty_minutes, v_now);
          perform public._su_kien('ngoi_phat', p.id,
            public.danh_xung(p, true) || ' ' || public.ten_goi(p) || ' lên Điện Tổ ngồi tụng kinh ' || p.penalty_minutes || ' phút.');
        end if;
      end if;
    end if;

    update public.profiles set
      penalty_minutes = p.penalty_minutes,
      penalty_topic_id = p.penalty_topic_id,
      penalty_question_id = p.penalty_question_id,
      penalty_assigned_at = p.penalty_assigned_at,
      penalty_seat_at = p.penalty_seat_at,
      penalty_elapsed = p.penalty_elapsed,
      last_seen_at = p.last_seen_at
    where id = p.id;

    if p.penalty_minutes > 0 and p.penalty_seat_at is null then
      select count(*) + 1 into v_position from public.profiles
      where id <> p.id and penalty_minutes > 0 and penalty_seat_at is null
        and last_seen_at > v_now - v_timeout
        and penalty_assigned_at < p.penalty_assigned_at;
    end if;
  else
    update public.profiles set last_seen_at = v_now where id = p.id;
    p.last_seen_at := v_now;
  end if;

  return jsonb_build_object(
    'done', v_done,
    'server_now', v_now,
    'state', public.state_json(p),
    'room', jsonb_build_object(
      'capacity', v_cap,
      'seated', coalesce((
        select jsonb_agg(jsonb_build_object(
                 'name', s.display_name,
                 'me', s.id = p.id,
                 'remaining', greatest(0, round(s.penalty_minutes * 60 - s.penalty_elapsed)))
               order by s.penalty_seat_at)
        from public.profiles s
        where s.penalty_minutes > 0 and s.penalty_seat_at is not null
          and s.last_seen_at > v_now - v_timeout), '[]'::jsonb),
      'waiting', (select count(*) from public.profiles w
                  where w.penalty_minutes > 0 and w.penalty_seat_at is null
                    and w.last_seen_at > v_now - v_timeout),
      'my_position', v_position
    )
  );
end
$$;

-- ---------------------------------------------------------------------
-- 6. Hương: thắp hương để Ông Tổ đẩy lên cấp khó hơn; đổi hương bằng công đức
-- ---------------------------------------------------------------------
create or replace function public.thap_huong()
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  p public.profiles := public._me_for_update();
  v_max integer := public.cfgi('max_level');
  v_from integer := p.level;
  v_to integer;
begin
  perform public._raise_if_penalty(p);
  if p.current_question_id is not null then
    raise exception 'Con trả lời xong quẻ đang xin rồi hãy thắp hương.';
  end if;
  if p.huong < 1 then
    raise exception 'Con chưa có nén hương nào.' using hint = 'no_incense';
  end if;
  if p.level >= v_max - 1 then
    raise exception 'Con đã đứng trước cửa sám hối. Cấp cuối phải tự trả lời đúng mới qua được.';
  end if;
  v_to := least(v_max - 1, p.level + public.cfgi('incense_level_boost'));

  update public.profiles set huong = huong - 1, level = v_to where id = p.id returning * into p;
  insert into public.huong_log (user_id, delta, reason, note)
  values (p.id, -1, 'thap_huong', 'Cấp ' || v_from || ' → ' || v_to);
  perform public._su_kien('thap_huong', p.id,
    public.danh_xung(p, true) || ' ' || public.ten_goi(p) || ' vừa thắp một nén hương. Ông Tổ nâng lên cấp ' || v_to || '.');

  return jsonb_build_object('from_level', v_from, 'to_level', v_to, 'state', public.state_json(p));
end
$$;

create or replace function public.doi_huong()
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  p public.profiles := public._me_for_update();
  v_cost integer := public.cfgi('incense_cost_merit');
begin
  if v_cost <= 0 then
    raise exception 'Thầy cô đã tắt đổi hương bằng công đức.';
  end if;
  if p.cong_duc < v_cost then
    raise exception 'Cần % công đức để đổi 1 nén hương, con đang có %.', v_cost, p.cong_duc;
  end if;
  update public.profiles set cong_duc = cong_duc - v_cost, huong = huong + 1
  where id = p.id returning * into p;
  insert into public.huong_log (user_id, delta, reason, note)
  values (p.id, 1, 'doi_cong_duc', v_cost || ' công đức');
  return jsonb_build_object('state', public.state_json(p));
end
$$;

-- Cộng hương cho một tài khoản (dùng chung cho thầy cô và webhook quà TikTok)
create or replace function public._cap_huong(
  p_tiktok text, p_user uuid, p_so integer, p_reason text, p_note text, p_by uuid
) returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_name text := public.normalize_tiktok(p_tiktok);
  p public.profiles;
begin
  if p_so is null or p_so = 0 or abs(p_so) > 1000 then
    raise exception 'Số hương không hợp lệ.';
  end if;
  if p_user is not null then
    select * into p from public.profiles where id = p_user for update;
  elsif v_name is not null then
    select * into p from public.profiles where tiktok_username = v_name for update;
  else
    raise exception 'Cần tên TikTok hoặc tài khoản học sinh.';
  end if;

  if p.id is null then
    if p_so < 0 or v_name is null then
      raise exception 'Không tìm thấy học sinh.';
    end if;
    insert into public.pending_gifts (tiktok_username, so_huong, note) values (v_name, p_so, p_note);
    perform public._su_kien('tang_qua', null,
      'Cảm ơn ' || v_name || ' đã tặng quà. ' || p_so || ' nén hương đang chờ chủ nhân gắn tên TikTok để nhận.');
    return jsonb_build_object('status', 'pending', 'tiktok_username', v_name, 'so', p_so);
  end if;

  if p.huong + p_so < 0 then
    raise exception 'Học sinh chỉ còn % nén hương.', p.huong;
  end if;
  update public.profiles set huong = huong + p_so where id = p.id returning * into p;
  insert into public.huong_log (user_id, delta, reason, note, granted_by)
  values (p.id, p_so, p_reason, p_note, p_by);
  if p_so > 0 then
    perform public._su_kien('tang_qua', p.id,
      case when p_reason = 'tiktok'
        then 'Cảm ơn ' || coalesce(p.tiktok_username, v_name, 'bạn') || ' đã tặng quà. ' || public.danh_xung(p, true) || ' ' || public.ten_goi(p)
             || ' nhận thêm ' || p_so || ' nén hương.'
        else 'Thầy cô tặng ' || public.danh_xung(p) || ' ' || public.ten_goi(p) || ' ' || p_so || ' nén hương.' end);
  end if;
  return jsonb_build_object('status', 'granted', 'display_name', p.display_name,
                            'tiktok_username', p.tiktok_username, 'huong', p.huong, 'so', p_so);
end
$$;

