    from (
      select a.id, a.created_at, a.choice, q.answer, q.content, q.options, q.explanation, q.level,
             t.name as topic_name, t.grade,
             exists (select 1 from public.attempts b
                     where b.user_id = v_uid and b.question_id = a.question_id
                       and b.is_correct and b.created_at > a.created_at) as redeemed
      from public.attempts a
